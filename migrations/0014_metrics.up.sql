CREATE TABLE metric_entries (
  id CHAR(26) NOT NULL PRIMARY KEY,
  organization_id CHAR(26) NOT NULL,
  client_id CHAR(26) NOT NULL,
  publication_id CHAR(26) NOT NULL,
  captured_on DATE NOT NULL,
  reach INT UNSIGNED NULL,
  impressions INT UNSIGNED NULL,
  likes INT UNSIGNED NULL,
  comments INT UNSIGNED NULL,
  shares INT UNSIGNED NULL,
  saves INT UNSIGNED NULL,
  clicks INT UNSIGNED NULL,
  video_views INT UNSIGNED NULL,
  followers_gained INT UNSIGNED NULL,
  source ENUM('manual','api') NOT NULL DEFAULT 'manual',
  notes VARCHAR(1000) NULL,
  created_by CHAR(26) NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at TIMESTAMP(3) NULL,
  KEY ix_metrics_org (organization_id, client_id, captured_on),
  KEY ix_metrics_pub (publication_id, captured_on),
  CONSTRAINT fk_metrics_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
  CONSTRAINT fk_metrics_client FOREIGN KEY (client_id) REFERENCES clients(id),
  CONSTRAINT fk_metrics_pub FOREIGN KEY (publication_id) REFERENCES publications(id),
  CONSTRAINT fk_metrics_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE profile_snapshots (
  id CHAR(26) NOT NULL PRIMARY KEY,
  organization_id CHAR(26) NOT NULL,
  client_id CHAR(26) NOT NULL,
  social_profile_id CHAR(26) NOT NULL,
  captured_on DATE NOT NULL,
  followers INT UNSIGNED NOT NULL,
  source ENUM('manual','api') NOT NULL DEFAULT 'manual',
  created_by CHAR(26) NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted_at TIMESTAMP(3) NULL,
  active_key VARCHAR(40) NULL,
  UNIQUE KEY uq_profile_snapshot_day (active_key),
  KEY ix_snapshots_org (organization_id, client_id, captured_on),
  CONSTRAINT fk_snapshots_org FOREIGN KEY (organization_id) REFERENCES organizations(id),
  CONSTRAINT fk_snapshots_client FOREIGN KEY (client_id) REFERENCES clients(id),
  CONSTRAINT fk_snapshots_profile FOREIGN KEY (social_profile_id) REFERENCES social_profiles(id),
  CONSTRAINT fk_snapshots_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
